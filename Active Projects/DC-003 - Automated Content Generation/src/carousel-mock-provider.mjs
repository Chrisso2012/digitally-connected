// DC-003-I004 — mock LLM provider.
//
// Implements the same shape any future real provider (OpenAI, Anthropic,
// a local model) will implement: an object with a `name` and an async
// `generateCarousel(prompt, context)` returning a raw text string — the
// Generator Orchestrator JSON.parses it exactly like it would a real
// completion, so swapping this for a real provider requires no downstream
// change. Deterministic: the same Topic Package always produces the same
// output, since content is derived only from context.topicPackage, never
// from randomness or the current time.
//
// Note: `content` fields could technically carry a "hashtags" array without
// violating the approved schema (each slide's `content` object is
// deliberately unconstrained there) — deliberately omitted anyway, since
// no slide type in DC-003-T002 §2 / config/templates.json defines a
// hashtags field for any of the six live templates. Adding one here would
// be inventing contract surface the rest of the pipeline doesn't expect.

import { SLIDE_ORDER } from "./carousel-slide-spec.mjs";

const MOCK_PROVIDER_NAME = "mock-provider-v1";
const STEP_TITLES = ["Understand", "Plan", "Act", "Review"];

function isBlank(value) {
  return typeof value !== "string" || value.trim().length === 0;
}

function sanitize(value) {
  return String(value).replace(/\s+/g, " ").trim();
}

function usablePoints(topicPackage) {
  return Array.isArray(topicPackage.supporting_points)
    ? topicPackage.supporting_points.filter((point) => !isBlank(point)).map(sanitize)
    : [];
}

function buildListItems(topicPackage) {
  const points = usablePoints(topicPackage);
  const items = points.slice(0, 4);
  let filler = 0;
  while (items.length < 3) {
    filler += 1;
    items.push(`Additional detail available on request (placeholder ${filler}).`);
  }
  return items;
}

function buildSteps(topicPackage) {
  const points = usablePoints(topicPackage);
  return STEP_TITLES.map((title, index) => ({
    title,
    description: points[index] ?? `Further detail on "${title.toLowerCase()}" is available on request.`,
  }));
}

function buildMockSlides(topicPackage) {
  const workingTitle = sanitize(topicPackage.working_title);
  const coreMessage = sanitize(topicPackage.core_message);
  const audience = sanitize(topicPackage.audience);
  const cta = sanitize(topicPackage.cta);

  const slideBuilders = {
    cover: () => ({
      eyebrow_text: "INSIGHT SERIES",
      headline_text: workingTitle,
      body_text: coreMessage,
    }),
    content: () => ({
      eyebrow_text: "KEY POINTS",
      headline_text: `What this means for ${audience}`,
      body_text: coreMessage,
      list_items: buildListItems(topicPackage),
    }),
    statistic: () => ({
      eyebrow_text: "BY THE NUMBERS",
      stat_value: "63%",
      supporting_stat_text: `of teams like ${audience} face this exact challenge — mock figure, illustrative only.`,
      stat_caption: "Placeholder statistic generated by the mock provider — not a verified figure.",
    }),
    quote: () => ({
      quote_text: `"${coreMessage}" — that's the shift we help teams make.`,
      attribution_name: "Illustrative client quote",
      attribution_role: audience,
    }),
    infographic: () => ({
      eyebrow_text: "HOW IT WORKS",
      headline_text: "A connected system, not a checklist",
      steps: buildSteps(topicPackage),
    }),
    cta: () => ({
      eyebrow_text: "READY WHEN YOU ARE",
      headline_text: workingTitle,
      body_text: coreMessage,
      button_label: cta,
    }),
  };

  return SLIDE_ORDER.map((slideType) => ({
    slide_type: slideType,
    content: slideBuilders[slideType](),
  }));
}

/**
 * Creates the mock provider. `generateCarousel` returns a raw JSON string
 * (never a pre-parsed object) so it behaves exactly like a real text-
 * completion API from the orchestrator's point of view.
 */
export function createMockProvider() {
  return {
    name: MOCK_PROVIDER_NAME,
    async generateCarousel(prompt, context = {}) {
      const { topicPackage } = context;
      if (!topicPackage) {
        throw new Error('mock provider requires context.topicPackage — call generateCarousel(prompt, { topicPackage })');
      }
      return JSON.stringify({ slides: buildMockSlides(topicPackage) });
    },
  };
}
