// DC-003-I023 — Production Metrics Store: the domain layer over a Storage
// Adapter (production-metrics-store-adapter.mjs). Mirrors
// finished-carousel-store.mjs (I015) exactly — this module knows nothing
// about files, only the Storage Adapter shape; it never imports node:fs.
// Every domain rule (duplicate rejection, existence checks, schema
// validation on both write and read, identifier safety, immutability)
// lives here; the adapter only ever moves bytes.
//
// Does NOT touch I015's own Finished Carousel Store or its files in any
// way — this is a genuinely separate store for a genuinely separate
// domain object (production-metrics.schema.json, not
// finished-carousel.schema.json).
//
// The canonical identifier is `metrics_id`
// (production-metrics.schema.json's own `^met_[A-Za-z0-9]+$` field,
// generated by production-metrics.mjs) — no second identifier was
// invented for this milestone.
//
// No replace()/update(): a Production Metrics Record is a point-in-time
// snapshot of what happened during one production run — it is never
// intentionally revised in place the way a Finished Carousel's approval
// state is. save() rejects a duplicate metrics_id outright; there is no
// sanctioned way to overwrite one.

import { createValidator } from "./validator.mjs";
import { deepFreezeClone } from "./immutable.mjs";
import { assertValidMetricsStoreAdapter } from "./production-metrics-store-adapter.mjs";
import {
  InvalidMetricsIdentifierError,
  MetricsRecordAlreadyExistsError,
  MetricsRecordNotFoundError,
  CorruptedMetricsRecordError,
  MetricsPersistenceError,
} from "./production-metrics-errors.mjs";

// Matches production-metrics.schema.json's own metrics_id pattern exactly
// — the one check standing between a caller-supplied string and a real
// filesystem path. No `/`, `\`, `.`, or whitespace can ever pass this,
// which is what actually blocks path traversal (`../../etc/passwd`,
// absolute paths, null bytes) — not a denylist of "bad" substrings.
const METRICS_ID_PATTERN = /^met_[A-Za-z0-9]+$/;

function checkIdentifier(identifier) {
  if (typeof identifier !== "string" || !METRICS_ID_PATTERN.test(identifier)) {
    throw new InvalidMetricsIdentifierError(identifier);
  }
}

function parseStoredContent(identifier, raw) {
  try {
    return JSON.parse(raw);
  } catch {
    // Node's JSON.parse SyntaxError embeds a snippet of the offending
    // text itself — passing it through could leak truncated/corrupted
    // file content. A fixed, content-free reason is used instead.
    throw new CorruptedMetricsRecordError(identifier, "stored content is not valid JSON");
  }
}

function validateStoredRecord(identifier, record, validator) {
  const validation = validator.validate("productionMetrics", record);
  if (!validation.valid) {
    throw new CorruptedMetricsRecordError(
      identifier,
      `stored content does not match production-metrics.schema.json (${validation.errors.length} error(s))`
    );
  }
}

function summarize(record) {
  return {
    metrics_id: record.metrics_id,
    request_id: record.request_id,
    execution_id: record.execution_id,
    carousel_id: record.carousel_id,
    status: record.status,
    recorded_at: record.recorded_at,
    total_cost: record.costs.total,
    currency: record.costs.currency,
  };
}

/**
 * Builds a Production Metrics Store over the given Storage Adapter.
 *
 * fields.adapter — required, must satisfy the Storage Adapter shape (see
 *   production-metrics-store-adapter.mjs); checked immediately via
 *   assertValidMetricsStoreAdapter().
 *
 * options.validator — inject a pre-built validator (used by tests).
 * options.rootDir — passed through when no validator is injected.
 *
 * Returns { name, save, get, list, findByExecutionId, exists }.
 */
export function createProductionMetricsStore({ adapter } = {}, options = {}) {
  assertValidMetricsStoreAdapter(adapter);
  const validator = options.validator ?? createValidator(options);

  /**
   * Persists a new, validated Production Metrics Record. Never mutates
   * the supplied object. Returns an immutable, deep-frozen copy of
   * exactly what was stored.
   *
   * Throws InvalidMetricsIdentifierError for a malformed metrics_id (a
   * caller-constructed object should never reach this — createProductionMetrics()
   * always produces a valid one — but this store never trusts that
   * blindly). Throws MetricsRecordAlreadyExistsError if a record already
   * exists for its metrics_id — save() never overwrites.
   */
  function save(metricsRecord) {
    const validation = validator.validate("productionMetrics", metricsRecord);
    if (!validation.valid) {
      throw new CorruptedMetricsRecordError(
        metricsRecord?.metrics_id ?? "(unknown)",
        `supplied record does not match production-metrics.schema.json (${validation.errors.length} error(s))`
      );
    }

    const identifier = metricsRecord.metrics_id;
    checkIdentifier(identifier);

    let alreadyExists;
    try {
      alreadyExists = adapter.exists(identifier);
    } catch (cause) {
      throw new MetricsPersistenceError(identifier, "exists-check", cause);
    }
    if (alreadyExists) {
      throw new MetricsRecordAlreadyExistsError(identifier);
    }

    const content = JSON.stringify(metricsRecord);
    try {
      adapter.write(identifier, content);
    } catch (cause) {
      throw new MetricsPersistenceError(identifier, "write", cause);
    }

    return deepFreezeClone(metricsRecord);
  }

  /**
   * Retrieves the stored Production Metrics Record for `identifier`.
   * Parses and validates the stored JSON before returning it. Returns an
   * immutable, deep-frozen object.
   *
   * Throws InvalidMetricsIdentifierError for a malformed identifier.
   * Throws MetricsRecordNotFoundError if no record exists. Throws
   * CorruptedMetricsRecordError if the stored content is not valid JSON,
   * or doesn't validate against production-metrics.schema.json.
   */
  function get(identifier) {
    checkIdentifier(identifier);

    let found;
    try {
      found = adapter.exists(identifier);
    } catch (cause) {
      throw new MetricsPersistenceError(identifier, "exists-check", cause);
    }
    if (!found) {
      throw new MetricsRecordNotFoundError(identifier);
    }

    let raw;
    try {
      raw = adapter.read(identifier);
    } catch (cause) {
      throw new MetricsPersistenceError(identifier, "read", cause);
    }

    const record = parseStoredContent(identifier, raw);
    validateStoredRecord(identifier, record, validator);

    return deepFreezeClone(record);
  }

  /**
   * Returns true if a stored record exists for `identifier`, without
   * reading or validating it.
   *
   * Throws InvalidMetricsIdentifierError for a malformed identifier.
   */
  function exists(identifier) {
    checkIdentifier(identifier);
    try {
      return adapter.exists(identifier);
    } catch (cause) {
      throw new MetricsPersistenceError(identifier, "exists-check", cause);
    }
  }

  /**
   * Returns a safe summary — { metrics_id, request_id, execution_id,
   * carousel_id, status, recorded_at, total_cost, currency } — for every
   * stored record, ordered deterministically by metrics_id ascending
   * (filesystem directory-listing order is not guaranteed across
   * platforms).
   *
   * Every stored record is parsed and validated exactly as get() does —
   * list() never silently skips or papers over a corrupted entry; it
   * fails on the first one found, naming which identifier is corrupted.
   */
  function list() {
    let identifiers;
    try {
      identifiers = adapter.list();
    } catch (cause) {
      throw new MetricsPersistenceError("(list)", "list", cause);
    }

    const summaries = identifiers.map((identifier) => {
      let raw;
      try {
        raw = adapter.read(identifier);
      } catch (cause) {
        throw new MetricsPersistenceError(identifier, "read", cause);
      }
      const record = parseStoredContent(identifier, raw);
      validateStoredRecord(identifier, record, validator);
      return summarize(record);
    });

    summaries.sort((a, b) => (a.metrics_id < b.metrics_id ? -1 : a.metrics_id > b.metrics_id ? 1 : 0));
    return deepFreezeClone(summaries);
  }

  /**
   * Returns every stored, full (not summarized) Production Metrics Record
   * whose `execution_id` matches, ordered deterministically by
   * `metrics_id` ascending. Returns an empty array if none match — never
   * throws for "no matches found", since "no metrics recorded for this
   * execution yet" is a legitimate, common state, not an error.
   *
   * Built on top of list()'s own full scan — this store has no secondary
   * index; a production-metrics directory is expected to stay small
   * enough (one file per production run) that a full scan is proportional
   * to this milestone's own scope.
   */
  function findByExecutionId(executionId) {
    let identifiers;
    try {
      identifiers = adapter.list();
    } catch (cause) {
      throw new MetricsPersistenceError("(list)", "list", cause);
    }

    const matches = [];
    for (const identifier of identifiers) {
      let raw;
      try {
        raw = adapter.read(identifier);
      } catch (cause) {
        throw new MetricsPersistenceError(identifier, "read", cause);
      }
      const record = parseStoredContent(identifier, raw);
      validateStoredRecord(identifier, record, validator);
      if (record.execution_id === executionId) {
        matches.push(record);
      }
    }

    matches.sort((a, b) => (a.metrics_id < b.metrics_id ? -1 : a.metrics_id > b.metrics_id ? 1 : 0));
    return deepFreezeClone(matches);
  }

  return { name: adapter.name, save, get, list, findByExecutionId, exists };
}
