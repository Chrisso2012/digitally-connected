// DC-003-I015 — Finished Carousel Store: the domain layer over a Storage
// Adapter (finished-carousel-store-adapter.mjs). Ensures generated and
// approved carousels no longer depend on transient CLI output files and
// can be reliably found, updated, and used by later approval and
// publishing workflows — per the I015 brief.
//
// This module knows nothing about files — only the Storage Adapter shape.
// It never imports node:fs. Every domain rule (duplicate rejection,
// existence checks, schema validation on both write and read, identifier
// safety, immutability) lives here; the adapter only ever moves bytes.
//
// Deliberately out of scope, per the approved I015 brief: database/cloud
// storage, n8n integration, a REST API, authentication, publishing logic,
// approval-state logic (this store persists whatever `approval` block a
// Finished Carousel already carries — see DC-003-I014 — it never decides
// or changes approval state itself), Execution Ledger changes, version
// history, concurrent multi-process locking, and cleanup/retention
// policies.
//
// The canonical identifier is `carousel_id`
// (finished-carousel.schema.json's own `^car_[A-Za-z0-9]+$` field,
// already generated by finished-carousel-builder.mjs since DC-003-I007)
// — no second identifier was invented for this milestone.

import { createValidator } from "./validator.mjs";
import { deepFreezeClone } from "./immutable.mjs";
import { assertValidCarouselStoreAdapter } from "./finished-carousel-store-adapter.mjs";
import {
  InvalidFinishedCarouselError,
  InvalidCarouselIdentifierError,
  CarouselAlreadyExistsError,
  CarouselNotFoundError,
  CarouselIdentifierMismatchError,
  CorruptedCarouselError,
  CarouselPersistenceError,
} from "./finished-carousel-store-errors.mjs";

// Matches finished-carousel.schema.json's own carousel_id pattern exactly
// — the one check standing between a caller-supplied string and a real
// filesystem path. No `/`, `\`, `.`, or whitespace can ever pass this,
// which is what actually blocks path traversal (`../../etc/passwd`,
// absolute paths, null bytes) — not a denylist of "bad" substrings.
const CAROUSEL_ID_PATTERN = /^car_[A-Za-z0-9]+$/;

function checkIdentifier(identifier) {
  if (typeof identifier !== "string" || !CAROUSEL_ID_PATTERN.test(identifier)) {
    throw new InvalidCarouselIdentifierError(identifier);
  }
}

function parseStoredContent(identifier, raw) {
  try {
    return JSON.parse(raw);
  } catch {
    // Node's JSON.parse SyntaxError embeds a snippet of the offending
    // text itself — passing it through could leak truncated/corrupted
    // file content. A fixed, content-free reason is used instead.
    throw new CorruptedCarouselError(identifier, "stored content is not valid JSON");
  }
}

function validateStoredCarousel(identifier, carousel, validator) {
  const validation = validator.validate("finishedCarousel", carousel);
  if (!validation.valid) {
    throw new CorruptedCarouselError(
      identifier,
      `stored content does not match finished-carousel.schema.json (${validation.errors.length} error(s))`
    );
  }
}

function summarize(carousel) {
  return {
    carousel_id: carousel.carousel_id,
    execution_id: carousel.execution_metadata.execution_id,
    topic_id: carousel.topic_id,
    generated_at: carousel.generated_at,
    overall_status: carousel.overall_status,
    slide_count: carousel.metadata.total_slides,
    approved: carousel.approval.approved,
    rejected: carousel.approval.rejected,
    published: carousel.approval.published,
  };
}

/**
 * Builds a Finished Carousel Store over the given Storage Adapter.
 *
 * fields.adapter — required, must satisfy the Storage Adapter shape (see
 *   finished-carousel-store-adapter.mjs); checked immediately via
 *   assertValidCarouselStoreAdapter().
 *
 * options.validator — inject a pre-built validator (used by tests).
 * options.rootDir — passed through when no validator is injected.
 *
 * Returns { name, save, get, list, replace, exists } — `name` is the
 * underlying adapter's own name, exposed for building safe storage
 * references (see DC-003-I016).
 */
export function createFinishedCarouselStore({ adapter } = {}, options = {}) {
  assertValidCarouselStoreAdapter(adapter);
  const validator = options.validator ?? createValidator(options);

  /**
   * Persists a new, validated Finished Carousel Object. Never mutates the
   * supplied object. Returns an immutable, deep-frozen copy of exactly
   * what was stored.
   *
   * Throws InvalidFinishedCarouselError if `finishedCarousel` fails
   * schema validation. Throws CarouselAlreadyExistsError if a record
   * already exists for its carousel_id — save() never overwrites.
   */
  function save(finishedCarousel) {
    const validation = validator.validate("finishedCarousel", finishedCarousel);
    if (!validation.valid) {
      throw new InvalidFinishedCarouselError(validation.errors);
    }

    const identifier = finishedCarousel.carousel_id;
    checkIdentifier(identifier);

    let alreadyExists;
    try {
      alreadyExists = adapter.exists(identifier);
    } catch (cause) {
      throw new CarouselPersistenceError(identifier, "exists-check", cause);
    }
    if (alreadyExists) {
      throw new CarouselAlreadyExistsError(identifier);
    }

    const content = JSON.stringify(finishedCarousel);
    try {
      adapter.write(identifier, content);
    } catch (cause) {
      throw new CarouselPersistenceError(identifier, "write", cause);
    }

    return deepFreezeClone(finishedCarousel);
  }

  /**
   * Retrieves the stored Finished Carousel for `identifier`. Parses and
   * validates the stored JSON before returning it — a corrupted or
   * schema-invalid stored file is never silently accepted. Returns an
   * immutable, deep-frozen object.
   *
   * Throws InvalidCarouselIdentifierError for a malformed identifier.
   * Throws CarouselNotFoundError if no record exists. Throws
   * CorruptedCarouselError if the stored content is not valid JSON, or
   * doesn't validate against finished-carousel.schema.json.
   */
  function get(identifier) {
    checkIdentifier(identifier);

    let found;
    try {
      found = adapter.exists(identifier);
    } catch (cause) {
      throw new CarouselPersistenceError(identifier, "exists-check", cause);
    }
    if (!found) {
      throw new CarouselNotFoundError(identifier);
    }

    let raw;
    try {
      raw = adapter.read(identifier);
    } catch (cause) {
      throw new CarouselPersistenceError(identifier, "read", cause);
    }

    const carousel = parseStoredContent(identifier, raw);
    validateStoredCarousel(identifier, carousel, validator);

    return deepFreezeClone(carousel);
  }

  /**
   * Returns true if a stored record exists for `identifier`, without
   * reading or validating it.
   *
   * Throws InvalidCarouselIdentifierError for a malformed identifier.
   */
  function exists(identifier) {
    checkIdentifier(identifier);
    try {
      return adapter.exists(identifier);
    } catch (cause) {
      throw new CarouselPersistenceError(identifier, "exists-check", cause);
    }
  }

  /**
   * Returns a safe summary — { carousel_id, execution_id, topic_id,
   * generated_at, overall_status, slide_count, approved, rejected,
   * published } — for every stored carousel, ordered deterministically by
   * carousel_id ascending (filesystem directory-listing order is not
   * guaranteed across platforms, so this store never relies on it).
   *
   * Every stored record is parsed and validated exactly as get() does —
   * list() never silently skips or papers over a corrupted entry; it
   * fails on the first one found, naming which identifier is corrupted.
   */
  function list() {
    let identifiers;
    try {
      identifiers = adapter.list();
    } catch (cause) {
      throw new CarouselPersistenceError("(list)", "list", cause);
    }

    const summaries = identifiers.map((identifier) => {
      let raw;
      try {
        raw = adapter.read(identifier);
      } catch (cause) {
        throw new CarouselPersistenceError(identifier, "read", cause);
      }
      const carousel = parseStoredContent(identifier, raw);
      validateStoredCarousel(identifier, carousel, validator);
      return summarize(carousel);
    });

    summaries.sort((a, b) => (a.carousel_id < b.carousel_id ? -1 : a.carousel_id > b.carousel_id ? 1 : 0));
    return deepFreezeClone(summaries);
  }

  /**
   * Replaces an existing stored Finished Carousel — the mechanism for
   * persisting a later approval, rejection, or publication transition
   * (DC-003-I014). This store implements no approval logic itself; it
   * only persists whatever `approval` block the supplied object already
   * carries.
   *
   * fields.identifier — the carousel_id of the record being replaced.
   * fields.finishedCarousel — the new, validated Finished Carousel Object
   *   to store in its place. Never mutated.
   *
   * Legal only when: a record already exists for `identifier`; the
   * supplied object's own carousel_id equals `identifier`; the supplied
   * object validates against finished-carousel.schema.json.
   *
   * Throws InvalidCarouselIdentifierError for a malformed identifier.
   * Throws InvalidFinishedCarouselError if the supplied object fails
   * schema validation. Throws CarouselIdentifierMismatchError if the
   * supplied object's carousel_id does not equal `identifier`. Throws
   * CarouselNotFoundError if no existing record is found for
   * `identifier`.
   */
  function replace({ identifier, finishedCarousel } = {}) {
    checkIdentifier(identifier);

    const validation = validator.validate("finishedCarousel", finishedCarousel);
    if (!validation.valid) {
      throw new InvalidFinishedCarouselError(validation.errors);
    }

    if (finishedCarousel.carousel_id !== identifier) {
      throw new CarouselIdentifierMismatchError(identifier, finishedCarousel.carousel_id);
    }

    let found;
    try {
      found = adapter.exists(identifier);
    } catch (cause) {
      throw new CarouselPersistenceError(identifier, "exists-check", cause);
    }
    if (!found) {
      throw new CarouselNotFoundError(identifier);
    }

    const content = JSON.stringify(finishedCarousel);
    try {
      adapter.write(identifier, content);
    } catch (cause) {
      throw new CarouselPersistenceError(identifier, "write", cause);
    }

    return deepFreezeClone(finishedCarousel);
  }

  // Exposed so a caller (e.g. DC-003-I016's Content Request Service) can
  // build a safe, non-path storage reference like
  // `${store.name}:${carouselId}` without ever touching the adapter or a
  // filesystem path directly.
  return { name: adapter.name, save, get, list, replace, exists };
}
