// DC-003-I025 — Publisher Result Store: the domain layer over a Storage
// Adapter (publisher-result-store-adapter.mjs). Mirrors
// production-metrics-store.mjs (I023) exactly — this module knows nothing
// about files, only the Storage Adapter shape; it never imports
// node:fs. Every domain rule (duplicate rejection, existence checks,
// schema validation on both write and read, identifier safety,
// immutability) lives here; the adapter only ever moves bytes.
//
// This is the repository's authoritative record of successful
// publications — per the I025 architectural principle, "the publisher
// performs work, the Publisher Result Store records the outcome." Nothing
// in this module publishes anything; it only persists and reads back
// results a publisher (google-drive-publisher-adapter.mjs, via
// production-asset-publisher-service.mjs) already produced.
//
// The canonical identifier is `publisher_result_id`
// (publisher-result.schema.json's own `^pub_[A-Za-z0-9]+$` field,
// generated by publisher-result.mjs) — no second identifier was invented.
//
// No replace()/update(): a Publisher Result is a point-in-time record of
// one successful publish event, never intentionally revised in place —
// a re-publish of the same carousel produces a SECOND, independent
// record (its own fresh publisher_result_id), not an overwrite. This
// deliberately preserves a full audit trail of every successful publish,
// not just the latest one.

import { createValidator } from "./validator.mjs";
import { deepFreezeClone } from "./immutable.mjs";
import { assertValidPublisherResultStoreAdapter } from "./publisher-result-store-adapter.mjs";
import {
  InvalidPublisherResultIdentifierError,
  PublisherResultAlreadyExistsError,
  PublisherResultNotFoundError,
  CorruptedPublisherResultError,
  PublisherResultPersistenceError,
} from "./publisher-result-errors.mjs";

// Matches publisher-result.schema.json's own publisher_result_id pattern
// exactly — the one check standing between a caller-supplied string and a
// real filesystem path. Blocks path traversal by construction, not by a
// denylist.
const PUBLISHER_RESULT_ID_PATTERN = /^pub_[A-Za-z0-9]+$/;

function checkIdentifier(identifier) {
  if (typeof identifier !== "string" || !PUBLISHER_RESULT_ID_PATTERN.test(identifier)) {
    throw new InvalidPublisherResultIdentifierError(identifier);
  }
}

function parseStoredContent(identifier, raw) {
  try {
    return JSON.parse(raw);
  } catch {
    // Node's JSON.parse SyntaxError embeds a snippet of the offending
    // text itself — passing it through could leak truncated/corrupted
    // file content. A fixed, content-free reason is used instead.
    throw new CorruptedPublisherResultError(identifier, "stored content is not valid JSON");
  }
}

function validateStoredResult(identifier, result, validator) {
  const validation = validator.validate("publisherResult", result);
  if (!validation.valid) {
    throw new CorruptedPublisherResultError(
      identifier,
      `stored content does not match publisher-result.schema.json (${validation.errors.length} error(s))`
    );
  }
}

function summarize(result) {
  return {
    publisher_result_id: result.publisher_result_id,
    carousel_id: result.carousel_id,
    execution_id: result.execution_id,
    asset_package_id: result.asset_package_id,
    provider: result.provider,
    destination: result.destination,
    published_at: result.published_at,
  };
}

/**
 * Builds a Publisher Result Store over the given Storage Adapter.
 *
 * fields.adapter — required, must satisfy the Storage Adapter shape (see
 *   publisher-result-store-adapter.mjs); checked immediately via
 *   assertValidPublisherResultStoreAdapter().
 *
 * options.validator — inject a pre-built validator (used by tests).
 * options.rootDir — passed through when no validator is injected.
 *
 * Returns { name, save, get, list, findByCarousel, findByExecution, exists }.
 */
export function createPublisherResultStore({ adapter } = {}, options = {}) {
  assertValidPublisherResultStoreAdapter(adapter);
  const validator = options.validator ?? createValidator(options);

  /**
   * Persists a new, validated Publisher Result. Never mutates the
   * supplied object. Returns an immutable, deep-frozen copy of exactly
   * what was stored.
   *
   * Throws PublisherResultAlreadyExistsError if a record already exists
   * for its publisher_result_id — save() never overwrites (a fresh ID is
   * generated per publish event by createPublisherResult(), so this only
   * fires for a genuinely duplicated ID, e.g. a caller bug).
   */
  function save(publisherResult) {
    const validation = validator.validate("publisherResult", publisherResult);
    if (!validation.valid) {
      throw new CorruptedPublisherResultError(
        publisherResult?.publisher_result_id ?? "(unknown)",
        `supplied record does not match publisher-result.schema.json (${validation.errors.length} error(s))`
      );
    }

    const identifier = publisherResult.publisher_result_id;
    checkIdentifier(identifier);

    let alreadyExists;
    try {
      alreadyExists = adapter.exists(identifier);
    } catch (cause) {
      throw new PublisherResultPersistenceError(identifier, "exists-check", cause);
    }
    if (alreadyExists) {
      throw new PublisherResultAlreadyExistsError(identifier);
    }

    const content = JSON.stringify(publisherResult);
    try {
      adapter.write(identifier, content);
    } catch (cause) {
      throw new PublisherResultPersistenceError(identifier, "write", cause);
    }

    return deepFreezeClone(publisherResult);
  }

  /**
   * Retrieves the stored Publisher Result for `identifier`. Parses and
   * validates the stored JSON before returning it. Returns an immutable,
   * deep-frozen object.
   *
   * Throws InvalidPublisherResultIdentifierError for a malformed
   * identifier. Throws PublisherResultNotFoundError if no record exists.
   * Throws CorruptedPublisherResultError if the stored content is not
   * valid JSON, or doesn't validate against publisher-result.schema.json.
   */
  function get(identifier) {
    checkIdentifier(identifier);

    let found;
    try {
      found = adapter.exists(identifier);
    } catch (cause) {
      throw new PublisherResultPersistenceError(identifier, "exists-check", cause);
    }
    if (!found) {
      throw new PublisherResultNotFoundError(identifier);
    }

    let raw;
    try {
      raw = adapter.read(identifier);
    } catch (cause) {
      throw new PublisherResultPersistenceError(identifier, "read", cause);
    }

    const result = parseStoredContent(identifier, raw);
    validateStoredResult(identifier, result, validator);

    return deepFreezeClone(result);
  }

  /**
   * Returns true if a stored record exists for `identifier`, without
   * reading or validating it.
   */
  function exists(identifier) {
    checkIdentifier(identifier);
    try {
      return adapter.exists(identifier);
    } catch (cause) {
      throw new PublisherResultPersistenceError(identifier, "exists-check", cause);
    }
  }

  /**
   * Returns a safe summary — { publisher_result_id, carousel_id,
   * execution_id, asset_package_id, provider, destination, published_at }
   * — for every stored record, ordered deterministically by
   * publisher_result_id ascending (filesystem directory-listing order is
   * not guaranteed across platforms).
   *
   * Every stored record is parsed and validated exactly as get() does —
   * list() never silently skips a corrupted entry; it fails on the first
   * one found, naming which identifier is corrupted.
   */
  function list() {
    let identifiers;
    try {
      identifiers = adapter.list();
    } catch (cause) {
      throw new PublisherResultPersistenceError("(list)", "list", cause);
    }

    const summaries = identifiers.map((identifier) => {
      let raw;
      try {
        raw = adapter.read(identifier);
      } catch (cause) {
        throw new PublisherResultPersistenceError(identifier, "read", cause);
      }
      const result = parseStoredContent(identifier, raw);
      validateStoredResult(identifier, result, validator);
      return summarize(result);
    });

    summaries.sort((a, b) => (a.publisher_result_id < b.publisher_result_id ? -1 : a.publisher_result_id > b.publisher_result_id ? 1 : 0));
    return deepFreezeClone(summaries);
  }

  // Shared full-scan helper for both find*() methods below — this store
  // has no secondary index (same "a directory this size stays proportional
  // to a full scan" reasoning production-metrics-store.mjs's own
  // findByExecutionId() already established for itself).
  function findWhere(predicate) {
    let identifiers;
    try {
      identifiers = adapter.list();
    } catch (cause) {
      throw new PublisherResultPersistenceError("(list)", "list", cause);
    }

    const matches = [];
    for (const identifier of identifiers) {
      let raw;
      try {
        raw = adapter.read(identifier);
      } catch (cause) {
        throw new PublisherResultPersistenceError(identifier, "read", cause);
      }
      const result = parseStoredContent(identifier, raw);
      validateStoredResult(identifier, result, validator);
      if (predicate(result)) {
        matches.push(result);
      }
    }

    matches.sort((a, b) => (a.published_at < b.published_at ? -1 : a.published_at > b.published_at ? 1 : 0));
    return deepFreezeClone(matches);
  }

  /**
   * Returns every stored, full (not summarized) Publisher Result whose
   * `carousel_id` matches, ordered by `published_at` ascending. Returns
   * an empty array if none match — never throws for "not published yet,"
   * since that's a legitimate, common state, not an error. This is the
   * primary lookup the Production Control Centre (DC-003-I024) uses to
   * answer "has this carousel been published."
   */
  function findByCarousel(carouselId) {
    return findWhere((result) => result.carousel_id === carouselId);
  }

  /**
   * Returns every stored, full Publisher Result whose `execution_id`
   * matches, ordered by `published_at` ascending. Returns an empty array
   * if none match.
   */
  function findByExecution(executionId) {
    return findWhere((result) => result.execution_id === executionId);
  }

  return { name: adapter.name, save, get, list, findByCarousel, findByExecution, exists };
}
